const assert=require('node:assert/strict');
const {compile,generate}=require('./math.js');
const v={r:.25,d:.5,s:-1,a:.6,w:.2};
assert.equal(compile('2+3*4')(v),14);
assert.equal(compile('-2^2')(v),-4);
assert.equal(compile('2^3^2')(v),512);
assert.equal(compile('max(2, sqrt(9)) + sin(pi/2)')(v),4);
assert.equal(compile('s*a + w')(v),-.39999999999999997);
for(const code of ['alert(1)','window.location','constructor(1)','r=3','1;2','sin()','2 3','min(1)','1e9'])assert.throws(()=>compile(code));
assert.throws(()=>compile('1/0')(v));
assert.throws(()=>compile('sqrt(-1)')(v));
assert.throws(()=>compile('('.repeat(30)+'1'+')'.repeat(30)));
const t={seed:'oak-01',length:'.7+.05*r',angle:'s*a',bend:'.1*r+w*.1',depth:5,spread:30,wind:.2,foliage:.6};
const a=generate(t),b=generate({...t});assert.deepEqual(a,b);assert.equal(a.branches.length,63);
assert.notDeepEqual(a,generate({...t,seed:'oak-02'}));
assert.deepEqual(a.branches,generate({...t,foliage:0}).branches);
assert.equal(generate({...t,foliage:0}).leaves.length,0);
assert.notDeepEqual(a.branches,generate({...t,angle:'s*a*.5'}).branches);
const bounded=generate({...t,length:'100',angle:'100',bend:'100',depth:7});assert.equal(bounded.branches.length,255);assert(bounded.clipped>0);
assert(bounded.branches.every(branch=>Object.values(branch).every(Number.isFinite)));
assert.throws(()=>generate({...t,depth:50}));
assert.throws(()=>generate({...t,length:'1/0'}));
console.log('Passed parser precedence, safe syntax, domain errors, seeded repeatability, independent foliage, formula effects, and growth bounds.');
